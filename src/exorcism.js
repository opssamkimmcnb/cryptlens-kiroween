import { analyzeCode } from './analyzer.js';

/**
 * Compare a cursed snippet against an exorcised refactor and compute delta stats.
 * @param {string} cursedCode
 * @param {string} purifiedCode
 * @param {'auto'|'javascript'|'python'} [language='auto']
 */
export function compareExorcism(cursedCode, purifiedCode, language = 'auto') {
  const before = analyzeCode(cursedCode, { language });
  const after = analyzeCode(purifiedCode, { language });

  const scoreDrop = before.metrics.curseScore - after.metrics.curseScore;
  const curseReductionPct = before.metrics.curseScore > 0
    ? Math.round((scoreDrop / before.metrics.curseScore) * 100)
    : 0;

  const complexityDrop = before.metrics.maxComplexity - after.metrics.maxComplexity;

  return {
    before,
    after,
    delta: {
      scoreDrop,
      curseReductionPct,
      complexityDrop,
      nestingDrop: before.metrics.maxNesting - after.metrics.maxNesting,
      cursesEliminated: before.metrics.curseCount - after.metrics.curseCount
    }
  };
}

/**
 * Generate a Markdown Ritual Audit Report for sharing or committing.
 * @param {ReturnType<typeof analyzeCode>} report
 * @param {string} [title='Untitled Specimen']
 */
export function exportMarkdownReport(report, title = 'Untitled Specimen') {
  const { metrics, tier, functions, curses, graph } = report;
  const lines = [
    `# CryptLens Haunted Code Audit — ${title}`,
    '',
    `- **Haunt Tier**: ${tier.label} (${metrics.curseScore}/100)`,
    `- **Language**: ${report.language}`,
    `- **Lines of Code**: ${metrics.codeLines} code / ${metrics.totalLines} total (${Math.round(metrics.commentRatio * 100)}% comments)`,
    `- **Functions Detected**: ${metrics.functionCount}`,
    `- **Max Cyclomatic Complexity**: ${metrics.maxComplexity} (avg ${metrics.avgComplexity})`,
    `- **Max Nesting Depth**: ${metrics.maxNesting}`,
    `- **Call Graph Edges**: ${graph.edges.length}`,
    '',
    '## Function Hotspots',
    ''
  ];

  if (functions.length === 0) {
    lines.push('_No named functions detected._');
  } else {
    lines.push('| Function | Lines | LOC | Complexity | Max Nesting |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const fn of functions) {
      lines.push(`| \`${fn.name}()\` | L${fn.startLine}–L${fn.endLine} | ${fn.loc} | ${fn.complexity} | ${fn.maxNesting} |`);
    }
  }

  lines.push('', '## Detected Curses & Exorcism Remedies', '');
  if (curses.length === 0) {
    lines.push('No curses detected. This codebase is sanctified.');
  } else {
    for (const c of curses) {
      lines.push(`- **[${c.severity.toUpperCase()}] L${c.line}: ${c.title}** — ${c.message} *Remedy:* ${c.remedy}`);
    }
  }

  lines.push('', '---', '_Generated by CryptLens for Kiroween 2026._');
  return lines.join('\n');
}
